"""Parser for the ImpulseM server protos (proto3 subset) of the layer 232 generator.

Reads protos/generated/v1/types.proto as generated by the ImpulseM server from the
TL scheme. Messages are read from open blocks and from one-line blocks, oneof blocks
are flattened into their message with the group name kept, and the optional and
repeated labels are kept as flags. The syntax, package, option, import and reserved
statements are skipped. Any other construct is an error, so a new shape in the
generated protos stops the generator instead of being dropped silently.

Usage from the generator: parse_protos.parse_proto_file(Path) returns
{message name: [field, ...]}, each field being {"name", "number", "type",
"repeated", "optional", "oneof"}, where "oneof" is the enclosing group name or None.
"""
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


Field = Dict[str, Any]
Fields = Dict[str, List[Field]]

BLOCK_COMMENT_RE: re.Pattern = re.compile(r"/\*.*?\*/", re.S)
LINE_COMMENT_RE: re.Pattern = re.compile(r"//.*$")
PACKAGE_RE: re.Pattern = re.compile(r"^package\s+[\w.]+\s*;$")
SKIPPED_RE: re.Pattern = re.compile(r"^(syntax|option|import|reserved)\b.*;$")
INLINE_MESSAGE_RE: re.Pattern = re.compile(r"^message\s+(\w+)\s*\{(.*)\}$")
OPEN_MESSAGE_RE: re.Pattern = re.compile(r"^message\s+(\w+)\s*\{$")
OPEN_ONEOF_RE: re.Pattern = re.compile(r"^oneof\s+(\w+)\s*\{$")
FIELD_RE: re.Pattern = re.compile(
    r"^(?:(optional|repeated)\s+)?([A-Za-z_][\w.]*)\s+([A-Za-z_]\w*)\s*=\s*(\d+)\s*;$"
)


def strip_comments(text: str) -> str:
    """Removes block and line comments. Block comments keep their newlines so line numbers stay right."""
    withoutBlocks: str = BLOCK_COMMENT_RE.sub(lambda m: "\n" * m.group(0).count("\n"), text)
    return "\n".join(LINE_COMMENT_RE.sub("", line) for line in withoutBlocks.split("\n"))


def add_message(messages: Fields, name: str, where: str) -> None:
    if name in messages:
        raise ValueError("duplicate message %s at %s" % (name, where))
    messages[name] = []


def add_field(
    messages: Fields,
    owner: str,
    oneofName: Optional[str],
    statement: str,
    where: str,
) -> None:
    fieldMatch: Optional[re.Match] = FIELD_RE.match(statement)
    if fieldMatch is None:
        raise ValueError("cannot parse field at %s: %s" % (where, statement))
    label: str = fieldMatch.group(1) or ""
    fieldName: str = fieldMatch.group(3)
    number: int = int(fieldMatch.group(4))
    if number <= 0:
        raise ValueError("field number must be positive at %s: %s" % (where, statement))
    if oneofName is not None and label:
        raise ValueError("label inside oneof at %s: %s" % (where, statement))
    fields: List[Field] = messages[owner]
    for existing in fields:
        if existing["name"] == fieldName:
            raise ValueError("duplicate field %s.%s at %s" % (owner, fieldName, where))
        if existing["number"] == number:
            raise ValueError("duplicate field number %s.%d at %s" % (owner, number, where))
    fields.append({
        "name": fieldName,
        "number": number,
        "type": fieldMatch.group(2),
        "repeated": label == "repeated",
        "optional": label == "optional",
        "oneof": oneofName,
    })


def parse_proto_text(text: str, where: str = "<proto>") -> Fields:
    messages: Fields = {}
    # Open scopes, innermost last: ("message", name) or ("oneof", name).
    stack: List[Tuple[str, str]] = []
    cleaned: str = strip_comments(text)
    for lineNumber, rawLine in enumerate(cleaned.split("\n"), start=1):
        line: str = rawLine.strip()
        if not line:
            continue
        position: str = "%s:%d" % (where, lineNumber)
        if PACKAGE_RE.match(line) or SKIPPED_RE.match(line):
            continue
        inlineMatch: Optional[re.Match] = INLINE_MESSAGE_RE.match(line)
        if inlineMatch is not None:
            if stack:
                raise ValueError("nested message is not supported at %s" % position)
            inlineName: str = inlineMatch.group(1)
            add_message(messages, inlineName, position)
            for statement in inlineMatch.group(2).split(";"):
                body: str = statement.strip()
                if not body or SKIPPED_RE.match(body + ";"):
                    continue
                add_field(messages, inlineName, None, body + ";", position)
            continue
        openMessageMatch: Optional[re.Match] = OPEN_MESSAGE_RE.match(line)
        if openMessageMatch is not None:
            if stack:
                raise ValueError("nested message is not supported at %s" % position)
            openName: str = openMessageMatch.group(1)
            add_message(messages, openName, position)
            stack.append(("message", openName))
            continue
        openOneofMatch: Optional[re.Match] = OPEN_ONEOF_RE.match(line)
        if openOneofMatch is not None:
            if not stack or stack[-1][0] != "message":
                raise ValueError("oneof outside a message at %s" % position)
            stack.append(("oneof", openOneofMatch.group(1)))
            continue
        if line == "}":
            if not stack:
                raise ValueError("unbalanced } at %s" % position)
            stack.pop()
            continue
        if not stack:
            raise ValueError("statement outside a message at %s: %s" % (position, line))
        ownerName: str = [n for kind, n in stack if kind == "message"][-1]
        groupName: Optional[str] = stack[-1][1] if stack[-1][0] == "oneof" else None
        add_field(messages, ownerName, groupName, line, position)
    if stack:
        raise ValueError("unterminated block in %s" % where)
    return messages


def parse_proto_file(path: Path) -> Fields:
    return parse_proto_text(path.read_text(encoding="utf-8"), path.name)
